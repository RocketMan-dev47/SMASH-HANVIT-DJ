const pick = (a) => a[Math.floor(Math.random() * a.length)];

// ctx: { edition, date, examDays }
export function drawFortune(edition, ctx = {}) {
  const d = ctx.date || new Date();
  const stars = 3 + Math.floor(Math.random() * 3);
  const subject = pick(SUBJECTS);
  let message;
  const r = Math.random();
  if (edition === 'suneung' && r < 0.7) message = pick(SUNEUNG);
  else if (typeof ctx.examDays === 'number' && ctx.examDays >= 0 && ctx.examDays <= 14 && r < 0.3) message = ctx.examDays === 0 ? '시험 당일! 아는 문제부터 차분하게, 넌 준비됐어요.' : `시험까지 ${ctx.examDays}일. 오늘 ${pick(SUBJECTS)} 한 단원이면 충분해요.`;
  else if (r < 0.42) message = `${pick(OPEN)} ${pick(ACTION).replace('{s}', subject)} ${pick(RESULT)}`;
  else if (r < 0.5) message = WEEK[d.getDay()];
  else if (r < 0.56) message = SEASON[d.getMonth() + 1];
  else message = pick(MESSAGES);
  return {
    stars, subject, place: pick(PLACES), item: pick(ITEMS), mood: pick(MOODS), moodScore: 70 + Math.floor(Math.random() * 31),
    color: pick(COLORS), number: pick(NUMBERS), message,
  };
}

